//! The Questie corrections module for Forever-new quests (ForeverQuestRelationTraces), in the
//! layout of the field extractor's corrections modules. Classic quests never go in: Forever
//! inherits their relations from Classic data, and disagreements are for a person to review first.
//! That includes quests with Forever-range ids that the ground truth files as inherited Classic
//! data.
//!
//! Quests with authored relations are included anyway. Authored corrections load after traces and
//! override per field, so this only fills fields the authors left empty. Prerequisites are one
//! slot, not two fields: Questie ignores preQuestGroup whenever preQuestSingle is set, so a
//! generated preQuestSingle would silently override an authored preQuestGroup. Quests with
//! authored prerequisites of either kind therefore get none from here.
//!
//! Like authored corrections, each quest's opening line carries its name, here with its Wowhead
//! page. Each field is preceded by the name and page of every quest it names, and ends with an
//! `-- Assumption:` saying why it is believed (see [`super::assumptions`]).

use super::assumptions::assumption;
use super::edges::QuestDomains;
use super::views::QuestView;
use crate::model::{QuestCatalog, QuestId, RelationField, RelationSet};
use crate::text::is_js_whitespace;
use indexmap::IndexMap;
use std::collections::BTreeMap;

pub const LUA_MODULE_NAME: &str = "ForeverQuestRelationTraces";

/// Per quest, the fields the module writes, in [`RelationField::ALL`] order. Scalar fields hold
/// their one value.
pub type LuaRecords = BTreeMap<QuestId, Vec<(RelationField, Vec<QuestId>)>>;

pub struct LuaHeader<'h> {
    pub candidate_files: &'h [&'h str],
    /// Largest inputCount among the candidate files: the episodes the trace signals read.
    pub session_count: usize,
    pub min_score: f64,
    pub generated_at: &'h str,
    /// File name of the review report combine publishes next to this module.
    pub review_file: &'h str,
}

pub fn forever_records(relations: &BTreeMap<QuestId, RelationSet>, authored: &BTreeMap<QuestId, RelationSet>, domains: &QuestDomains) -> LuaRecords {
    let mut records = LuaRecords::new();
    for (&quest_id, set) in relations.iter().filter(|(&quest_id, _)| domains.is_forever_new(quest_id)) {
        let authored_prerequisites = authored
            .get(&quest_id)
            .is_some_and(|set| set.contains_key(&RelationField::PreQuestSingle) || set.contains_key(&RelationField::PreQuestGroup));
        let record: Vec<(RelationField, Vec<QuestId>)> = RelationField::ALL
            .into_iter()
            .filter(|field| !(authored_prerequisites && matches!(field, RelationField::PreQuestSingle | RelationField::PreQuestGroup)))
            .filter_map(|field| set.get(&field).filter(|values| !values.is_empty()).map(|values| (field, values.clone())))
            .collect();
        if !record.is_empty() {
            records.insert(quest_id, record);
        }
    }
    records
}

pub fn wowhead_quest_url(quest_id: QuestId) -> String {
    format!("https://wowhead.com/forever/quest={quest_id}")
}

/// Whitespace runs (including line breaks) collapsed to one space, so a comment can never spill
/// into code. None when nothing is left.
fn flat_comment(text: &str) -> Option<String> {
    let flat = text.split(is_js_whitespace).filter(|word| !word.is_empty()).collect::<Vec<_>>().join(" ");
    (!flat.is_empty()).then_some(flat)
}

fn trailing_comment(text: Option<&str>) -> String {
    text.and_then(flat_comment).map_or_else(String::new, |flat| format!(" -- {flat}"))
}

fn lua_value(field: RelationField, values: &[QuestId]) -> String {
    if field.is_scalar() {
        values[0].to_string()
    } else {
        let values: Vec<String> = values.iter().map(ToString::to_string).collect();
        format!("{{{}}}", values.join(","))
    }
}

/// The module, commented from the same views the review renders.
pub fn forever_relations_lua(records: &LuaRecords, header: &LuaHeader, views: &IndexMap<QuestId, QuestView>, catalog: &QuestCatalog) -> String {
    let name_of = |quest_id: QuestId| catalog.quest(quest_id).and_then(|quest| quest.name.as_deref()).filter(|name| !name.is_empty());
    let module = LUA_MODULE_NAME;
    let mut lines = vec![
        format!("---@class {module}"),
        format!("local {module} = QuestieLoader:CreateModule(\"{module}\")"),
        String::new(),
        "---@type QuestieDB".to_owned(),
        "local QuestieDB = QuestieLoader:ImportModule(\"QuestieDB\")".to_owned(),
        String::new(),
        "-- Generated by Exporters (tools/corrections-extractor)".to_owned(),
        format!(
            "-- Quest relations from `npm run relations -- combine` (min score {}); review: {}, published next to this module",
            header.min_score, header.review_file
        ),
        format!("-- Candidate files: {}", header.candidate_files.join(", ")),
        "-- Each Assumption names the strongest trace observation (independent characters), how many signals agree and the combined score".to_owned(),
        format!("-- Sessions aggregated: {}", header.session_count),
        format!("-- Generated at: {}", header.generated_at),
        format!("function {module}:Load()"),
        "    local questKeys = QuestieDB.questKeys".to_owned(),
        String::new(),
        "    return {".to_owned(),
    ];
    for (&quest_id, record) in records {
        let entity = [name_of(quest_id).map(str::to_owned), Some(wowhead_quest_url(quest_id))]
            .into_iter()
            .flatten()
            .collect::<Vec<_>>()
            .join(" ");
        lines.push(format!("        [{quest_id}] = {{{}", trailing_comment(Some(&entity))));
        let view = views.get(&quest_id);
        for (field, values) in record {
            // The review's quest label (`id "name"`), so the ids in the value and the Assumption are easy to match.
            for &target in view.map_or(&[][..], |view| view.relation(*field)) {
                let label = match name_of(target) {
                    Some(name) => format!("{target} \"{name}\" {}", wowhead_quest_url(target)),
                    None => format!("{target} {}", wowhead_quest_url(target)),
                };
                if let Some(flat) = flat_comment(&label) {
                    lines.push(format!("            -- {flat}"));
                }
            }
            let comment = view.and_then(|view| assumption(view, *field));
            lines.push(format!(
                "            [questKeys.{field}] = {},{}",
                lua_value(*field, values),
                trailing_comment(comment.as_deref())
            ));
        }
        lines.push("        },".to_owned());
    }
    lines.push("    }".to_owned());
    lines.push("end".to_owned());
    lines.join("\n")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::combine::edges::{Claim, Domain, EdgeKey, EdgeKind, Reference, Source};
    use crate::combine::resolve::Outcome;
    use crate::combine::views::EdgeView;
    use crate::model::{CatalogQuest, GroundTruth, GroundTruthTiers};
    use crate::test_support::{catalog, catalog_quest};

    #[test]
    fn writes_forever_new_quests_only_and_leaves_authored_prerequisites_alone() {
        use RelationField::{ExclusiveTo, NextQuestInChain, PreQuestGroup, PreQuestSingle};
        // 65593 has a Forever-range id but is inherited Classic data, so it is review-only.
        let relations = BTreeMap::from([
            (92000, RelationSet::from([(PreQuestSingle, vec![1]), (NextQuestInChain, vec![2])])),
            (92001, RelationSet::from([(PreQuestSingle, vec![3]), (ExclusiveTo, vec![92002])])),
            (500, RelationSet::from([(PreQuestSingle, vec![4])])),
            (65593, RelationSet::from([(NextQuestInChain, vec![65597])])),
        ]);
        // Questie ignores preQuestGroup once preQuestSingle is set, so writing one here would override the authored AND list.
        let authored = BTreeMap::from([(92000, RelationSet::from([(PreQuestGroup, vec![1, 5])]))]);
        let truth = GroundTruth {
            tiers: GroundTruthTiers {
                authored_forever: authored.clone(),
                inherited_classic: BTreeMap::from([(500, RelationSet::new()), (65593, RelationSet::new())]),
            },
            ..GroundTruth::default()
        };

        let records = forever_records(&relations, &authored, &QuestDomains::new(&truth));

        assert_eq!(records[&92000], [(NextQuestInChain, vec![2])]);
        assert_eq!(records[&92001], [(PreQuestSingle, vec![3]), (ExclusiveTo, vec![92002])]);
        assert_eq!(records.keys().copied().collect::<Vec<_>>(), [92000, 92001]);
    }

    #[test]
    fn names_and_links_the_quest_and_every_quest_a_field_names_and_ends_the_field_with_its_assumption() {
        let claims = [Claim {
            source: Source {
                signal: "handoff",
                field: RelationField::NextQuestInChain,
            },
            field: RelationField::NextQuestInChain,
            score: 0.96,
            support: 31,
            contradict: 0,
            evidence: &[],
        }];
        let relations = RelationSet::from([(RelationField::NextQuestInChain, vec![92001])]);
        let view = QuestView {
            quest_id: 92000,
            name: Some("Book Inventory"),
            domain: Domain::Forever,
            reference: Reference::None,
            relations: &relations,
            edges: vec![EdgeView {
                key: EdgeKey::new(EdgeKind::Next, 92000, 92001),
                field: RelationField::NextQuestInChain,
                target: 92001,
                probability: 0.97,
                held_out: false,
                outcome: Outcome::Accepted,
                because: None,
                status: None,
                claims: &claims,
                context: &[],
                contributions: &[],
            }],
            reference_only: vec![],
            hints: vec![],
            note: None,
        };
        let catalog = catalog([
            CatalogQuest {
                name: Some("Book Inventory".into()),
                ..catalog_quest(92000)
            },
            CatalogQuest {
                name: Some("Rascally Rodents".into()),
                ..catalog_quest(92001)
            },
        ]);
        let header = LuaHeader {
            candidate_files: &["handoff", "offer-set"],
            session_count: 12,
            min_score: 0.9,
            generated_at: "1970-01-01T00:00:00.000Z",
            review_file: "relations-review.md",
        };
        let records = LuaRecords::from([(92000, vec![(RelationField::NextQuestInChain, vec![92001])])]);

        let lua = forever_relations_lua(&records, &header, &IndexMap::from([(92000, view)]), &catalog);

        assert!(lua
            .contains("-- Quest relations from `npm run relations -- combine` (min score 0.9); review: relations-review.md, published next to this module\n"));
        assert!(lua.contains("-- Candidate files: handoff, offer-set\n"));
        assert!(lua.contains(concat!(
            "        [92000] = { -- Book Inventory https://wowhead.com/forever/quest=92000\n",
            "            -- 92001 \"Rascally Rodents\" https://wowhead.com/forever/quest=92001\n",
            "            [questKeys.nextQuestInChain] = 92001, -- Assumption: turning it in led straight to 92001 (31 characters), score 0.970\n",
            "        },\n",
        )));
        assert!(lua.ends_with("    }\nend"));
    }
}
