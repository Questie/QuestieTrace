// Turns quest XP rows into a paste-ready Questie support file for `QuestXP.db`
// (see QuestieDB `support/Forever/QuestXP/`). Unlike the forever*Traces modules it is plain
// data: the rows are added to the base table that the support loader already assigned.

import type { CorrectionsWriterHeader } from "./corrections-writer";

export interface QuestXpRow {
  level: number;
  xp: number;
}

export function writeQuestXpLua(rows: Map<number, QuestXpRow>, header: CorrectionsWriterHeader): string {
  const lines: string[] = [
    "---@type QuestXP",
    'local QuestXP = QuestieLoader:ImportModule("QuestXP")',
    "",
    "-- Generated by QuestieTrace extract (tools/corrections-extractor)",
    `-- Source trace files: ${header.sourceFileNames.length}`,
    `-- Sessions aggregated: ${header.sessionCount}`,
    `-- Generated at: ${header.generatedAt.toISOString()}`,
  ];

  for (const id of [...rows.keys()].sort((a, b) => a - b)) {
    const { level, xp } = rows.get(id)!;
    lines.push(`QuestXP.db[${id}] = {${level}, ${xp}}`);
  }
  return lines.join("\n");
}
